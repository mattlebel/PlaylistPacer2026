export const POPULAR_SONGS: Song[] = LIST.map(([title, artist]) => ({ title, artist }));

const norm = (s: string) =>
  s
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9 ]/g, " ")
    .replace(/\s+/g, " ")
    .trim();

const INDEX = POPULAR_SONGS.map((s) => ({ s, title: norm(s.title), artist: norm(s.artist) }));

/** Songs from the built-in list that match what's typed, best first. Every word must appear in the title or artist. */
export function suggestSongs(query: string, limit = 8): Song[] {
  const q = norm(query);
  if (q.length < 2) return [];
  const words = q.split(" ");
  const scored: { s: Song; score: number }[] = [];
  for (const { s, title, artist } of INDEX) {
    const hay = `${title} ${artist}`;
    if (!words.every((w) => hay.includes(w))) continue;
    let score = 0;
    if (title.startsWith(q)) score += 6;
    else if (title.includes(q)) score += 4;
    if (artist.startsWith(q)) score += 3;
    for (const w of words) if (` ${title} `.includes(` ${w}`)) score += 1;
    scored.push({ s, score });
  }
  return scored
    .sort((a, b) => b.score - a.score || a.s.title.length - b.s.title.length)
    .slice(0, limit)
    .map((x) => x.s);
}

/** "Juice - Lizzo", "Juice – Lizzo" or "Juice by Lizzo" → a song. Null if there's no artist. */
export function parseTypedSong(text: string): Song | null {
  const t = text.trim().replace(/\s+/g, " ");
  // Split at whichever separator comes last, so titles can contain one too:
  // "Stand By Me by Ben E. King", "Mr. Brightside - Remastered by The Killers".
  const seps = [...t.matchAll(/ (?:[-–—]|by) /gi)];
  const last = seps.at(-1);
  if (!last || last.index === 0) return null;
  const [title, artist] = [t.slice(0, last.index).trim(), t.slice(last.index + last[0].length).trim()];
  if (!title || !artist) return null;
  return { title: title.slice(0, 200), artist: artist.slice(0, 200) };
}
